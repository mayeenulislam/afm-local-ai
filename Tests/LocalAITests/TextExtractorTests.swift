import CoreText
import Foundation
import PDFKit
import SQLite3
import XCTest
@testable import LocalAI

/// Locks the file-type extraction pipeline (DOC-001..009, DB-001..011) with
/// real fixtures: PDF (PDFKit-read text with `[[page:N]]` markers), DOCX
/// (ZIProtection via hardened `textutil`), PPTX (own zip parser with slide
/// numbering + speaker notes), and SQLite (schema/sample-row introspection).
final class TextExtractorTests: XCTestCase {
    private var tempDir: URL!

    override func setUp() {
        super.setUp()
        tempDir = FileManager.default.temporaryDirectory
            .appendingPathComponent("TextExtractorTests_\(UUID().uuidString)")
        try? FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
    }

    override func tearDown() {
        try? FileManager.default.removeItem(at: tempDir)
        super.tearDown()
    }

    private func makeFile(_ data: Data, name: String, kind: WorkspaceFileKind) throws -> WorkspaceFile {
        let url = tempDir.appendingPathComponent(name)
        try data.write(to: url)
        let byteCount = (try FileManager.default.attributesOfItem(atPath: url.path)[.size] as? NSNumber)?.int64Value ?? 0
        return WorkspaceFile(url: url, relativePath: name, kind: kind, byteCount: byteCount)
    }

    private func makeFile(_ text: String, name: String, kind: WorkspaceFileKind) throws -> WorkspaceFile {
        try makeFile(Data(text.utf8), name: name, kind: kind)
    }

    // MARK: - PDF

    private func makePDF(pages: [String], to url: URL) throws {
        var mediaBox = CGRect(x: 0, y: 0, width: 612, height: 792)
        guard let context = CGContext(url as CFURL, mediaBox: &mediaBox, nil) else {
            throw NSError(domain: "TextExtractorTests", code: 1)
        }
        for pageText in pages {
            context.beginPDFPage(nil)
            let font = CTFontCreateWithName("Helvetica" as CFString, 12, nil)
            let text = pageText as CFString
            let attributed = CFAttributedStringCreateMutable(kCFAllocatorDefault, 0)!
            CFAttributedStringReplaceString(attributed, CFRangeMake(0, 0), text)
            CFAttributedStringSetAttribute(attributed, CFRangeMake(0, CFStringGetLength(text)), kCTFontAttributeName, font)
            let line = CTLineCreateWithAttributedString(attributed)
            context.textPosition = CGPoint(x: 72, y: 700)
            CTLineDraw(line, context)
            context.endPDFPage()
        }
        context.closePDF()
    }

    func testPDFExtractionPreservesPageMarkersAndText() throws {
        let url = tempDir.appendingPathComponent("report.pdf")
        try makePDF(pages: ["Quasar redshift data", "Magnetar spin details"], to: url)
        let file = try makeFile(Data(contentsOf: url), name: "report.pdf", kind: .pdf)

        let result = try TextExtractor().extract(from: file)

        XCTAssertTrue(result.text.contains("[[page:1]]"))
        XCTAssertTrue(result.text.contains("[[page:2]]"))
        XCTAssertTrue(result.text.contains("Quasar redshift data"))
        XCTAssertTrue(result.text.contains("Magnetar spin details"))
    }

    func testPDFExtractionTruncatesAtCharacterCap() throws {
        let url = tempDir.appendingPathComponent("big.pdf")
        try makePDF(pages: [String(repeating: "a", count: 200), String(repeating: "b", count: 200)], to: url)
        let file = try makeFile(Data(contentsOf: url), name: "big.pdf", kind: .pdf)

        let result = try TextExtractor(maxExtractedCharacters: 10).extract(from: file)

        XCTAssertTrue(result.text.contains("PDF text truncated"))
    }

    func testPDFTooLargeThrows() throws {
        // Default cap is 100 MB; exercising it needs a real 100 MB PDF, so this
        // covers the generic maxBytes guard via a small maxBytes extractor.
        let extractor = TextExtractor(maxBytes: 1_500_000, maxSQLiteBytes: 10, maxPDFBytes: 10, maxExtractedCharacters: 10)
        let file = try makeFile("tiny pdf bytes", name: "small.pdf", kind: .pdf)
        XCTAssertThrowsError(try extractor.extract(from: file)) { error in
            XCTAssertEqual(error as? TextExtractionError ?? .unreadable, .tooLarge)
        }
    }

    func testInvalidPDFThrowsUnreadable() throws {
        let file = try makeFile("this is not a real pdf file", name: "fake.pdf", kind: .pdf)
        XCTAssertThrowsError(try TextExtractor().extract(from: file)) { error in
            XCTAssertEqual(error as? TextExtractionError ?? .unreadable, .unreadable)
        }
    }

    // MARK: - DOCX

    /// `textutil` is strict about OOXML structure, so the fixture is generated by
    /// `textutil` itself (txt -> docx) rather than hand-rolled — guaranteeing a
    /// genuinely valid document the extractor must read back.
    private func makeDOCX(to url: URL) throws {
        let dir = tempDir.appendingPathComponent("docx_src_\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let txt = dir.appendingPathComponent("body.txt")
        try "Hello DOCX world\n".write(to: txt, atomically: true, encoding: .utf8)

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/textutil")
        process.arguments = ["-convert", "docx", txt.path]
        process.standardOutput = FileHandle.nullDevice
        process.standardError = FileHandle.nullDevice
        try process.run()
        process.waitUntilExit()

        let generated = dir.appendingPathComponent("body.docx")
        guard process.terminationStatus == 0, FileManager.default.fileExists(atPath: generated.path) else {
            throw NSError(domain: "TextExtractorTests", code: 4, userInfo: [NSLocalizedDescriptionKey: "textutil failed to generate DOCX fixture"])
        }
        if FileManager.default.fileExists(atPath: url.path) {
            try FileManager.default.removeItem(at: url)
        }
        try FileManager.default.copyItem(at: generated, to: url)
        try? FileManager.default.removeItem(at: dir)
    }

    func testDOCXExtractionReturnsParagraphText() throws {
        let url = tempDir.appendingPathComponent("notes.docx")
        try makeDOCX(to: url)
        let file = try makeFile(Data(contentsOf: url), name: "notes.docx", kind: .document)

        let result = try TextExtractor().extract(from: file)

        XCTAssertTrue(result.text.contains("Hello DOCX world"))
    }

    func testDOCXFilenameStartingWithDashDoesNotBecomeOption() throws {
        // textutil must treat a filename beginning with `-` as a path, not an
        // option (the extractor passes a `--` separator before the path).
        let url = tempDir.appendingPathComponent("-tricky.docx")
        try makeDOCX(to: url)
        let file = try makeFile(Data(contentsOf: url), name: "-tricky.docx", kind: .document)

        let result = try TextExtractor().extract(from: file)

        XCTAssertTrue(result.text.contains("Hello DOCX world"))
    }

    func testCorruptDOCXPassesThroughWithoutCrashing() throws {
        // textutil (and therefore the extractor) falls back to reading a
        // corrupt .docx as plain text rather than erroring. That is benign
        // (no crash, no subprocess injection), but it is pass-through: the
        // raw bytes enter context as text. Product decision pending on whether
        // corrupt documents should be rejected explicitly instead.
        let file = try makeFile("not an ooxml zip at all", name: "broken.docx", kind: .document)
        let result = try TextExtractor().extract(from: file)
        XCTAssertEqual(result.text, "not an ooxml zip at all")
    }

    // MARK: - PPTX

    private func makePPTX(to url: URL, slides: [(String, String)], notes: [(String, String)]) throws {
        var entries: [(String, Data)] = slides.map { ("ppt/slides/\($0.0)", Data($0.1.utf8)) }
        entries += notes.map { ("ppt/notesSlides/\($0.0)", Data($0.1.utf8)) }
        try StoredZip.data(entries: entries).write(to: url)
    }

    func testPPTXExtractionPreservesSlideNumberingSpeakerNotesAndEntityDecoding() throws {
        let url = tempDir.appendingPathComponent("deck.pptx")
        try makePPTX(
            to: url,
            slides: [
                ("slide1.xml",
                 """
                 <?xml version="1.0"?><p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><p:cSld><p:spTree><p:sp><p:txBody><a:p><a:r><a:t>Welcome &amp; Overview</a:t></a:r></a:p></p:txBody></p:sp></p:spTree></p:cSld></p:sld>
                 """),
                ("slide2.xml",
                 """
                 <?xml version="1.0"?><p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><p:cSld><p:spTree><p:sp><p:txBody><a:p><a:r><a:t>Next &lt;slide&gt;</a:t></a:r></a:p></p:txBody></p:sp></p:spTree></p:cSld></p:sld>
                 """)
            ],
            notes: [
                ("notesSlide1.xml",
                 """
                 <?xml version="1.0"?><p:notes xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><p:cSld><p:spTree><p:sp><p:txBody><a:p><a:r><a:t>These are speaker notes for slide one</a:t></a:r></a:p></p:txBody></p:sp></p:spTree></p:cSld></p:notes>
                 """)
            ]
        )
        let file = try makeFile(Data(contentsOf: url), name: "deck.pptx", kind: .presentation)

        let result = try TextExtractor().extract(from: file)

        XCTAssertTrue(result.text.contains("[[slide:1]]"))
        XCTAssertTrue(result.text.contains("[[slide:2]]"))
        XCTAssertTrue(result.text.contains("Welcome & Overview"), "XML entities must be decoded: \(result.text)")
        XCTAssertTrue(result.text.contains("Next <slide>"), "XML entities must be decoded: \(result.text)")
        XCTAssertTrue(result.text.contains("Speaker notes:"))
        XCTAssertTrue(result.text.contains("These are speaker notes for slide one"))
        let slide1 = try XCTUnwrap(result.text.range(of: "[[slide:1]]")).lowerBound
        let notes = try XCTUnwrap(result.text.range(of: "These are speaker notes for slide one")).lowerBound
        let slide2 = try XCTUnwrap(result.text.range(of: "[[slide:2]]")).lowerBound
        XCTAssertLessThan(slide1, notes, "slide 1 must come before its notes")
        XCTAssertLessThan(notes, slide2, "slide 1 notes must come before slide 2")
    }

    func testCorruptPPTXThrows() throws {
        let file = try makeFile("definitely not a zip", name: "broken.pptx", kind: .presentation)
        XCTAssertThrowsError(try TextExtractor().extract(from: file))
    }

    // MARK: - SQLite

    private func execSQL(_ sql: String, in database: OpaquePointer) throws {
        guard sqlite3_exec(database, sql, nil, nil, nil) == SQLITE_OK else {
            throw NSError(domain: "TextExtractorTests", code: Int(sqlite3_errcode(database)))
        }
    }

    private func makeSQLite(tables: [String]) throws -> URL {
        let url = tempDir.appendingPathComponent("fixture.db")
        var database: OpaquePointer?
        guard sqlite3_open(url.path, &database) == SQLITE_OK, let database else {
            throw NSError(domain: "TextExtractorTests", code: 2)
        }
        defer { sqlite3_close(database) }
        for table in tables {
            try execSQL(table, in: database)
        }
        return url
    }

    func testSQLiteExtractionDescribesSchemaAndSampleRows() throws {
        let url = try makeSQLite(tables: [
            "CREATE TABLE users (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL);",
            "INSERT INTO users (name, email) VALUES ('Ada', 'ada@example.com');",
            "INSERT INTO users (name, email) VALUES ('Grace', 'grace@example.com');",
            "CREATE VIEW user_names AS SELECT name FROM users;"
        ])
        let file = try makeFile(Data(contentsOf: url), name: "fixture.db", kind: .data)

        let result = try TextExtractor().extract(from: file).text

        let table = try XCTUnwrap(result.range(of: "## Table: users")).lowerBound
        let view = try XCTUnwrap(result.range(of: "## View: user_names")).lowerBound
        XCTAssertLessThan(table, view, "tables must be listed before views")
        XCTAssertTrue(result.contains("CREATE TABLE users"))
        XCTAssertTrue(result.contains("CREATE VIEW user_names"))
        XCTAssertTrue(result.contains("- id INTEGER primary key"))
        XCTAssertTrue(result.contains("- name TEXT not null"))
        XCTAssertTrue(result.contains("| id | name | email |"), "sample-row header table must be rendered")
        XCTAssertTrue(result.contains("| 1 | Ada | ada@example.com |"), "sample rows must be rendered: \(result)")
        XCTAssertTrue(result.contains("| 2 | Grace | grace@example.com |"))
    }

    func testSQLiteExtractionWithNoUserTables() throws {
        let url = try makeSQLite(tables: [])
        let file = try makeFile(Data(contentsOf: url), name: "empty.db", kind: .data)

        let result = try TextExtractor().extract(from: file).text

        XCTAssertTrue(result.contains("No user tables or views were found."))
    }

    func testSQLiteExtractionCapsLongCells() throws {
        let longValue = String(repeating: "x", count: 300)
        let url = try makeSQLite(tables: [
            "CREATE TABLE notes (data TEXT NOT NULL);",
            "INSERT INTO notes (data) VALUES ('\(longValue)');"
        ])
        let file = try makeFile(Data(contentsOf: url), name: "notes.db", kind: .data)

        let result = try TextExtractor().extract(from: file).text

        XCTAssertTrue(result.contains("..."), "long cells must be truncated: \(result)")
        XCTAssertFalse(result.contains(String(repeating: "x", count: 300)), "full cell must not leak: \(result)")
    }

    func testCorruptSQLiteThrows() throws {
        let file = try makeFile("this is not a sqlite database", name: "broken.db", kind: .data)
        XCTAssertThrowsError(try TextExtractor().extract(from: file))
    }
}

/// Minimal stored-method ZIP writer used to build DOCX/PPTX fixtures without
/// shelling out to `zip`/`ditto`. Only what `ZipArchive` reads is filled in;
/// CRC values are not validated by the reader.
private struct StoredZip {
    static func data(entries: [(name: String, data: Data)]) -> Data {
        var local = Data()
        var central = Data()
        var offset: UInt32 = 0

        for entry in entries {
            let nameBytes = Data(entry.name.utf8)

            var localHeader = Data()
            localHeader.append(u32(0x0403_4b50))
            localHeader.append(u16(20))
            localHeader.append(u16(0x0800))
            localHeader.append(u16(0))
            localHeader.append(u16(0))
            localHeader.append(u16(0x21))
            localHeader.append(u32(0))
            localHeader.append(u32(UInt32(entry.data.count)))
            localHeader.append(u32(UInt32(entry.data.count)))
            localHeader.append(u16(UInt16(nameBytes.count)))
            localHeader.append(u16(0))
            localHeader.append(nameBytes)
            localHeader.append(entry.data)
            local.append(localHeader)

            var centralEntry = Data()
            centralEntry.append(u32(0x0201_4b50))
            centralEntry.append(u16(20))
            centralEntry.append(u16(20))
            centralEntry.append(u16(0x0800))
            centralEntry.append(u16(0))
            centralEntry.append(u16(0))
            centralEntry.append(u16(0x21))
            centralEntry.append(u32(0))
            centralEntry.append(u32(UInt32(entry.data.count)))
            centralEntry.append(u32(UInt32(entry.data.count)))
            centralEntry.append(u16(UInt16(nameBytes.count)))
            centralEntry.append(u16(0))
            centralEntry.append(u16(0))
            centralEntry.append(u16(0))
            centralEntry.append(u16(0))
            centralEntry.append(u32(0))
            centralEntry.append(u32(offset))
            centralEntry.append(nameBytes)
            central.append(centralEntry)

            offset += UInt32(localHeader.count)
        }

        var eocd = Data()
        eocd.append(u32(0x0605_4b50))
        eocd.append(u16(0))
        eocd.append(u16(0))
        eocd.append(u16(UInt16(entries.count)))
        eocd.append(u16(UInt16(entries.count)))
        eocd.append(u32(UInt32(central.count)))
        eocd.append(u32(offset))
        eocd.append(u16(0))

        var result = local
        result.append(central)
        result.append(eocd)
        return result
    }

    private static func u16(_ value: UInt16) -> Data {
        withUnsafeBytes(of: value.littleEndian) { Data($0) }
    }

    private static func u32(_ value: UInt32) -> Data {
        withUnsafeBytes(of: value.littleEndian) { Data($0) }
    }
}